// <img> markup with responsive sizes. Files live at /assets/media/<key>-<w>.webp
export function img(key, { sizes = "100vw", cls = "", eager = false } = {}) {
  const p = photos[key];
  if (!p) throw new Error(`Unknown photo: ${key}`);
  return `<img class="${cls}" src="/assets/media/${key}-1600.webp" srcset="/assets/media/${key}-800.webp 800w, /assets/media/${key}-1600.webp 1600w" sizes="${sizes}" alt="${p.alt}" ${eager ? 'fetchpriority="high"' : 'loading="lazy"'} decoding="async" />`;
}
